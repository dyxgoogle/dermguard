def generate_ingredient_rules(output_path: Path | None = None) -> dict[str, Any]:
    """Deterministically writes `ingredient_rules.json` to disk.

    Args:
        output_path: Optional override path for testing; defaults to
            `dermguard/data/ingredient_rules.json`.

    Returns:
        Generated dataset dictionary.
    """
    target = output_path or DEFAULT_RULES_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    dataset = build_seed_dataset()
    target.write_text(json.dumps(dataset, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return dataset


